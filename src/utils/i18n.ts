const STORAGE_LANG_KEY = 'ai_quiz_screen_language_v1';

export function getStoredLanguage(): string {
  try {
    const saved = localStorage.getItem(STORAGE_LANG_KEY);
    if (saved && SUPPORTED_LANGUAGES.some((l) => l.code === saved)) {
      return saved;
    }
  } catch {}
  return 'en';
}

export function saveStoredLanguage(langCode: string): void {
  try {
    localStorage.setItem(STORAGE_LANG_KEY, langCode);
  } catch {}
}

export function translate(key: string, langCode: string, fallback?: string): string {
  const entry = TRANSLATIONS[key];
  if (!entry) return fallback || key;
  return entry[langCode] || entry['en'] || fallback || key;
}

export function translateTopic(topic: string, langCode: string): string {
  switch (topic) {
    case 'AI basics':
      return translate('topic_ai_basics', langCode, topic);
    case 'Machine learning':
      return translate('topic_machine_learning', langCode, topic);
    case 'LLMs and prompting':
      return translate('topic_llms_and_prompting', langCode, topic);
    case 'AI tools':
      return translate('topic_ai_tools', langCode, topic);
    case 'Data and privacy':
      return translate('topic_data_and_privacy', langCode, topic);
    case 'Ethics and safety':
      return translate('topic_ethics_and_safety', langCode, topic);
    case 'AI in the workplace':
      return translate('topic_ai_in_the_workplace', langCode, topic);
    default:
      return topic;
  }
}

export function translateDifficulty(diff: string, langCode: string): string {
  switch (diff) {
    case 'Beginner':
      return translate('diff_beginner', langCode, diff);
    case 'Intermediate':
      return translate('diff_intermediate', langCode, diff);
    case 'Advanced':
      return translate('diff_advanced', langCode, diff);
    default:
      return diff;
  }
}

export function translateProficiency(level: string, langCode: string): string {
  switch (level) {
    case 'Novice':
      return translate('level_novice', langCode, level);
    case 'Learner':
      return translate('level_learner', langCode, level);
    case 'Practitioner':
      return translate('level_practitioner', langCode, level);
    case 'Expert':
      return translate('level_expert', langCode, level);
    default:
      return level;
  }
}
